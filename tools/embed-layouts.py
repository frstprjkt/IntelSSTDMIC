#!/usr/bin/env python3
"""Embed Layouts.plist at build time.

- writes build/LayoutsData.cpp with a generated C++ initializer for every layout
- writes the built Info.plist with IntelSSTDMLayouts / IntelSSTDMLayoutIDs
"""
import argparse
import plistlib
import sys


def fail(msg):
    print(f"embed-layouts: {msg}", file=sys.stderr)
    sys.exit(1)


def cstr(value):
    if value is None:
        value = ""
    out = []
    for ch in str(value):
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.append("\\x%02x" % ord(ch))
    return '"' + "".join(out) + '"'


def platform(value):
    v = str(value or "").lower()
    if v in ("tgl", "tigerlake", "tiger-lake", "1"):
        return "PlatformFamily::TigerLake"
    if v in ("cml", "cometlake", "comet-lake", "cnl", "cannonlake", "2"):
        return "PlatformFamily::CometLake"
    return "PlatformFamily::Unknown"


def u32(entry, key, default):
    value = entry.get(key, default)
    return int(value) if isinstance(value, int) else default


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--layouts", required=True)
    ap.add_argument("--info", required=True)
    ap.add_argument("--info-out", required=True)
    ap.add_argument("--cpp-out", required=True)
    args = ap.parse_args()

    try:
        with open(args.layouts, "rb") as f:
            doc = plistlib.load(f)
    except Exception as e:
        fail(f"cannot read {args.layouts}: {e}")

    layouts = doc.get("Layouts")
    if not isinstance(layouts, list) or not layouts:
        fail("Layouts.plist has no Layouts array")

    ids = []
    for i, entry in enumerate(layouts):
        if not isinstance(entry, dict):
            fail(f"layout #{i} is not a dictionary")
        lid = entry.get("id")
        if not isinstance(lid, int) or lid <= 0:
            fail(f"layout #{i}: id must be an integer > 0 (0 is reserved for disabled)")
        if lid in ids:
            fail(f"duplicate layout id {lid}")
        if not entry.get("platform"):
            fail(f"layout {lid}: missing platform")
        if not entry.get("engine"):
            fail(f"layout {lid}: missing engine")
        ids.append(lid)

    with open(args.cpp_out, "w") as f:
        f.write("// Generated by tools/embed-layouts.py - do not edit.\n")
        f.write('#include "LayoutConfig.hpp"\n#include <IOKit/IOLib.h>\n\n')
        f.write('extern "C" void sstdmEmbeddedLayouts(LayoutRegistry &registry) {\n')
        for entry in layouts:
            lid = entry["id"]
            dsp = entry.get("dsp") or {}
            hda = entry.get("hda") or {}
            codecs = entry.get("codecs") or []
            maps = hda.get("channelMap") or [0, 1]
            rates = hda.get("sampleRates") or [dsp.get("sourceRate", 48000)]
            bits = hda.get("bits") or [16, 24, 32]

            f.write("    {\n        LayoutConfig p {};\n        p.valid = true;\n")
            f.write(f"        p.id = {lid};\n")
            f.write(f"        snprintf(p.name, sizeof(p.name), \"%s\", {cstr(entry.get('name', ''))});\n")
            f.write(f"        p.platform = {platform(entry.get('platform'))};\n")
            f.write(f"        snprintf(p.engine, sizeof(p.engine), \"%s\", {cstr(entry.get('engine', ''))});\n")
            f.write(f"        p.micCount = {u32(entry, 'micCount', 2)};\n")
            f.write("        p.codecCount = %d;\n" % min(len(codecs), 4))
            for n, codec in enumerate(codecs[:4]):
                f.write(f"        snprintf(p.codecs[{n}], sizeof(p.codecs[{n}]), \"%s\", {cstr(codec)});\n")
            f.write(f"        snprintf(p.firmware, sizeof(p.firmware), \"%s\", {cstr(dsp.get('firmware', ''))});\n")
            f.write(f"        p.streamIndex = {u32(dsp, 'streamIndex', 6)};\n")
            f.write(f"        p.pcmTag = {u32(dsp, 'pcmTag', 7)};\n")
            f.write(f"        p.pipelineId = {u32(dsp, 'pipelineId', 57)};\n")
            f.write(f"        p.sourceRate = {u32(dsp, 'sourceRate', 48000)};\n")
            f.write(f"        p.sourceChannels = {u32(dsp, 'sourceChannels', 4)};\n")
            f.write(f"        p.sourceBits = {u32(dsp, 'sourceBits', 32)};\n")
            f.write(f"        p.gainPercent = {u32(dsp, 'gain', 100)};\n")
            f.write(f"        p.outputChannels = {u32(hda, 'outputChannels', 2)};\n")
            for n, value in enumerate(maps[:8]):
                f.write(f"        p.channelMap[{n}] = {int(value)};\n")
            f.write(f"        p.safetyFrames = {u32(hda, 'safetyFrames', 57)};\n")
            f.write(f"        p.sampleRateCount = {min(len(rates), 8)};\n")
            for n, value in enumerate(rates[:8]):
                f.write(f"        p.sampleRates[{n}] = {int(value)};\n")
            f.write(f"        p.bitDepthCount = {min(len(bits), 8)};\n")
            for n, value in enumerate(bits[:8]):
                f.write(f"        p.bitDepths[{n}] = {int(value)};\n")
            f.write(f"        p.keepAliveSec = {u32(entry, 'keepAliveSec', 60)};\n")
            f.write(f"        p.allowD0i3 = {'true' if entry.get('allowD0i3', False) else 'false'};\n")
            f.write("        registry.addLayout(p);\n    }\n")
        f.write("}\n")

    try:
        with open(args.info, "rb") as f:
            info = plistlib.load(f)
    except Exception as e:
        fail(f"cannot read {args.info}: {e}")

    info["IntelSSTDMLayouts"] = doc
    info["IntelSSTDMLayoutIDs"] = ids
    with open(args.info_out, "wb") as f:
        plistlib.dump(info, f, sort_keys=False)

    print(f"embed-layouts: {len(layouts)} layout(s) ids={ids}")


if __name__ == "__main__":
    main()
